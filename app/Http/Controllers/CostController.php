<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use App\Models\Cost;
use App\Models\Project;
use App\Models\Phase;
use App\Services\GeminiCostEstimator;
use Inertia\Inertia;

class CostController extends Controller
{
    //
    public function index(Project $project)
    {
        $project->load(['costs.phase', 'phases']);
        return Inertia::render('projects/financials', [
            'project' => $project,
        ]);
    }

    public function store(Request $request, Project $project)
    {
        $validated = $request->validate([
            'phase_id' => 'required|exists:phases,id',
            'amount' => 'required|numeric',
            'title' => 'required|string',
            'type' => 'required|string',
            'notes' => 'nullable|string'
        ]);

        $project->costs()->create(array_merge($validated, [
            'company_id' => $request->user()->company_id,
        ]));

        return redirect()->back();
    }

    public function generateEstimate(Request $request, Project $project, Phase $phase, GeminiCostEstimator $estimator)
    {
        $plotCount = $project->plots()->count();
        $estimatedAmount = $estimator->generateEstimate($project->name, $phase->name, $plotCount);

        if ($estimatedAmount) {
            $project->costs()->create([
                'company_id' => $request->user()->company_id,
                'phase_id' => $phase->id,
                'title' => "AI Baseline: {$phase->name}",
                'amount' => $estimatedAmount,
                'type' => 'estimated',
                'notes' => 'Auto-generated by Gemini AI based on ' . $plotCount . ' units.',
            ]);
        }

        return redirect()->back();
    }
}
